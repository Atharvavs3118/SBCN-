/**
 * Online translation caller to server-side endpoint (/api/translate)
 * for dynamic strings that are not part of the standard pre-compiled dictionary.
 */
export async function translateOnline(text: string, targetLang: SupportedLanguage): Promise<string> {
  if (!text || targetLang === 'en') return text;
  
  const cacheKey = `${targetLang}:${text}`;
  if (dynamicTranslationCache[cacheKey]) {
    return dynamicTranslationCache[cacheKey];
  }

  try {
    const langObj = SUPPORTED_LANGUAGES.find((l) => l.code === targetLang);
    const targetName = langObj ? langObj.name : targetLang;

    const response = await fetch('/api/translate', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        text,
        targetLanguage: targetName,
      }),
    });

    if (response.ok) {
      const data = await response.json();
      if (data.translatedText) {
        dynamicTranslationCache[cacheKey] = data.translatedText;
        return data.translatedText;
      }
    }
  } catch (err) {
    console.warn('Online translation failed, using source:', err);
  }

  return text;
}
